import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { categories, converters } from "../src/index.js";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(scriptDirectory, "../src/index.d.ts");
const checkOnly = process.argv.includes("--check");

/**
 * @param {string} category
 * @returns {string}
 */
function typeName(category) {
  return category.charAt(0).toUpperCase() + category.slice(1);
}

/**
 * @param {string} value
 * @returns {string}
 */
function quote(value) {
  return JSON.stringify(value);
}

/**
 * @returns {string}
 */
function generateTypes() {
  const lines = [
    "// This file is generated by scripts/generate-types.js.",
    "// Do not edit it by hand. Run `npm run build:types` instead.",
    "",
  ];

  for (const category of categories) {
    const name = typeName(category);
    const unitNames = converters[category].units;
    const aliasNames = Object.keys(converters[category].aliases);

    lines.push(`export type ${name}Unit =`);
    unitNames.forEach((unit, index) => {
      const terminator = index === unitNames.length - 1 ? ";" : "";
      lines.push(`  | ${quote(unit)}${terminator}`);
    });
    lines.push("");

    if (aliasNames.length === 0) {
      lines.push(`export type ${name}Alias = never;`);
    } else {
      lines.push(`export type ${name}Alias =`);
      aliasNames.forEach((alias, index) => {
        const terminator = index === aliasNames.length - 1 ? ";" : "";
        lines.push(`  | ${quote(alias)}${terminator}`);
      });
    }
    lines.push("");

    lines.push(`export interface ${name}Converter {`);
    lines.push(`  /** The units supported by the ${category} converter. */`);
    lines.push(`  readonly units: readonly ${name}Unit[];`);
    lines.push(`  /** The aliases accepted by the ${category} converter. */`);
    lines.push(
      `  readonly aliases: Readonly<Record<${name}Alias, ${name}Unit>>;`
    );
    lines.push(
      `  /** Convert a value between two supported ${category} units or aliases. */`
    );
    lines.push(
      `  convert(fromUnit: ${name}Unit | ${name}Alias, toUnit: ${name}Unit | ${name}Alias, value: number): number;`
    );
    lines.push(
      `  resolve(unit: ${name}Unit | ${name}Alias): ${name}Unit;`
    );

    for (const fromUnit of unitNames) {
      for (const toUnit of unitNames) {
        lines.push(`  ${fromUnit}To${toUnit}(value: number): number;`);
      }
    }

    lines.push("}");
    lines.push("");
  }

  lines.push(
    `export type Category = ${categories.map(quote).join(" | ")};`,
    ""
  );
  lines.push("export interface CategoryUnits {");
  for (const category of categories) {
    lines.push(`  ${category}: ${typeName(category)}Unit;`);
  }
  lines.push("}", "");
  lines.push("export type CategoryUnit<C extends Category> = CategoryUnits[C];");
  lines.push("");
  lines.push("export interface CategoryAliases {");
  for (const category of categories) {
    lines.push(`  ${category}: ${typeName(category)}Alias;`);
  }
  lines.push("}", "");
  lines.push("export type CategoryAlias<C extends Category> = CategoryAliases[C];");
  lines.push("");

  for (const category of categories) {
    const name = typeName(category);
    lines.push(`export declare const ${category}: ${name}Converter;`);
  }

  lines.push("");
  lines.push("export declare const converters: {");
  for (const category of categories) {
    lines.push(`  readonly ${category}: ${typeName(category)}Converter;`);
  }
  lines.push("};");
  lines.push("");
  lines.push("export declare const categories: readonly Category[];");
  lines.push("");
  lines.push("export declare const units: {");
  for (const category of categories) {
    lines.push(
      `  readonly ${category}: readonly ${typeName(category)}Unit[];`
    );
  }
  lines.push("};");
  lines.push("");
  lines.push("export declare const aliases: {");
  for (const category of categories) {
    const name = typeName(category);
    lines.push(
      `  readonly ${category}: Readonly<Record<${name}Alias, ${name}Unit>>;`
    );
  }
  lines.push("};");
  lines.push("");
  lines.push(
    `/**`,
    ` * Convert a value between any two units in the same category.`,
    ` *`,
    ` * @example`,
    ` * convert("length", "Meter", "Foot", 1); // 3.280839895013123`,
    ` */`,
    `export declare function convert<C extends Category>(`,
    `  category: C,`,
    `  fromUnit: CategoryUnit<C> | CategoryAlias<C>,`,
    `  toUnit: CategoryUnit<C> | CategoryAlias<C>,`,
    `  value: number`,
    `): number;`,
    "",
    `/**`,
    ` * Round a finite number to a fixed number of decimal places.`,
    ` *`,
    ` * @example`,
    ` * round(3.14159, 2); // 3.14`,
    ` */`,
    `export declare function round(value: number, decimals?: number): number;`,
    ""
  );
  lines.push(
    `/**`,
    ` * Parse a quantity string such as "5 ft 3 in" or "1 h 30 min".`,
    ` *`,
    ` * When \`toUnit\` is omitted the first unit in the input is used as the target.`,
    ` */`,
    `export declare function parseQuantity<C extends Category>(`,
    `  category: C,`,
    `  input: string,`,
    `  toUnit?: CategoryUnit<C> | CategoryAlias<C>`,
    `): number;`,
    ""
  );
  lines.push(
    `export interface FormatOptions {`,
    `  locale?: string | string[];`,
    `  decimals?: number;`,
    `  significantDigits?: number;`,
    `  useGrouping?: boolean;`,
    `}`,
    ""
  );
  lines.push(
    `/**`,
    ` * Format a number and unit as a localized string.`,
    ` */`,
    `export declare function formatQuantity(`,
    `  value: number,`,
    `  unit: string,`,
    `  options?: FormatOptions`,
    `): string;`,
    ""
  );
  lines.push(
    `/**`,
    ` * Return true if \`year\` is a leap year in the proleptic Gregorian calendar.`,
    ` */`,
    `export declare function isLeapYear(year: number): boolean;`,
    "",
    `/**`,
    ` * Return the number of days in a Gregorian month (1-12).`,
    ` */`,
    `export declare function daysInMonth(year: number, month: number): number;`,
    ""
  );

  return lines.join("\n");
}

const generated = generateTypes();

if (checkOnly) {
  let existing = "";
  try {
    existing = readFileSync(outputPath, "utf8");
  } catch {
    // Missing file is reported below.
  }

  if (existing !== generated) {
    console.error(
      "src/index.d.ts is out of date. Run `npm run build:types` to regenerate it."
    );
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, generated);
}
